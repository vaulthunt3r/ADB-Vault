test('last operation expires automatically; a newer result gets its own display time and history stays intact', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-09T18:00:00Z') })
  await page.clock.pauseAt(new Date('2026-10-09T18:00:01Z'))
  const last = page.getByRole('button', { name: 'Last operation — open Activity' })
  await page.evaluate(state => window.backendTest.emit({ type: 'appAction', state: { ...state, status: 'success' } }), action)
  await expect(last).toBeVisible()
  await page.clock.runFor(7999)
  await expect(last).toBeVisible()
  await page.clock.runFor(1)
  await expect(last).toHaveCount(0)
  await page.evaluate(state => window.backendTest.emit({ type: 'appAction', state: { ...state, operationId: 'failed-run', status: 'error' } }), action)
  await expect(last).toBeVisible()
  await page.clock.runFor(14999)
  await expect(last).toBeVisible()
  await page.evaluate(state => window.backendTest.emit({ type: 'appAction', state: { ...state, operationId: 'retry-run', status: 'success' } }), action)
  await page.clock.runFor(1)
  await expect(last).toBeVisible()
  await page.clock.runFor(7999)
  await expect(last).toHaveCount(0)
  await page.evaluate(state => window.backendTest.emit({ type: 'appAction', state: { ...state, operationId: 'another-failure', status: 'error' } }), action)
  await expect(last).toBeVisible()
  await page.clock.runFor(15000)
  await expect(last).toHaveCount(0)
  await page.getByRole('navigation').getByRole('button', { name: 'Activity', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Session events' }).getByRole('row')).toHaveCount(5)
})
