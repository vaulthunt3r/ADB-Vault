test('firmware denial has a concise inspector; original output survives copy and export, and selection clears both panels', async ({ page }) => {
  const message = "Exception occurred while executing 'disable-user':\njava.lang.SecurityException: Cannot disable system packages.\n"
    + Array.from({ length: 20 }, (_, i) => `    at com.android.server.pm.PackageManagerServiceImpl.shouldRestrictEnabledSettingsChange(PackageManagerServiceImpl.java:${1064 + i})`).join('\n')
  await page.evaluate(({ state, message }) => {
    window.backendTest.emit({ type: 'appAction', state: { ...state, action: 'disable', status: 'error', total: 1, completed: 1, message, batch: { ...state.batch!, items: [{ ...state.batch!.items[0], system: true, status: 'error', message }] } } })
    window.backendTest.emit({ type: 'activity', source: 'connection', tone: 'success', text: 'Phone connected successfully.' })
  }, { state: action, message })
  await page.getByRole('button', { name: 'Last operation — open Activity' }).click()
  const inspector = page.getByRole('complementary', { name: 'Context sidebar' })
  const summary = inspector.getByRole('region', { name: 'Event summary' })
  const details = page.getByRole('region', { name: 'Operation details' })
  await expect(summary).toContainText('Notes')
  await expect(summary).toContainText('The phone’s firmware blocked disabling this system application through ADB.')
  await expect(inspector).not.toContainText('SecurityException')
  await expect(inspector).not.toContainText('PackageManagerServiceImpl')
  await expect(details).toContainText('java.lang.SecurityException: Cannot disable system packages.')
  await expect(details).toContainText('PackageManagerServiceImpl.java:1083')
  await page.getByRole('button', { name: 'Copy operation', exact: true }).click()
  expect(await page.evaluate(() => window.backendTest.clipboardWrites.at(-1))).toContain(message)
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export shown' }).click()
  const { readFile } = await import('node:fs/promises')
  expect(await readFile((await (await download).path())!, 'utf8')).toContain(message)
  await page.screenshot({ path: 'desktop-test-results/activity-summary.png' })
  await page.getByRole('button', { name: 'Event: Phone connected successfully.' }).click()
  await expect(summary).toHaveText('Phone connected successfully.')
  await expect(details).not.toContainText('SecurityException')
  await page.getByRole('button', { name: 'Event: Disable · 1 applications' }).click()
  await expect(summary).toContainText('firmware blocked')
  await page.getByRole('button', { name: 'Close operation details' }).click()
  await expect(details).toHaveCount(0)
  await expect(summary).toHaveCount(0)
  await expect(inspector).toContainText('Select an event to read its details.')
  await page.getByRole('button', { name: 'Event: Disable · 1 applications' }).click()
  await page.getByRole('button', { name: 'Clear session history' }).click()
  await expect(summary).toHaveCount(0)
  await expect(inspector).not.toContainText('firmware blocked')
})

