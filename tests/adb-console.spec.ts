import { test, expect, type Page } from '@playwright/test'
import { installBackendFixture, connectionEvent } from './backend-fixture'

const phone = { id: 'phone', serial: '192.168.1.2:4444', name: 'Test phone', method: 'Wi-Fi' as const, status: 'connected' as const, android: '16', endpoint: '192.168.1.2:4444', lastSeen: '', known: true, canDetach: true, transportId: '7' }
async function finish(page: Page, code = 0) {
  await page.evaluate(code => {
    const state = window.backendTest.snapshot.adbConsole!
    window.backendTest.emit({ type: 'adbConsole', state: { ...state, revision: state.revision + 1, run: { ...state.run!, status: code ? 'error' : 'success', exitCode: code, output: [{ stream: 'stdout', text: 'Android model\n' }, { stream: 'stderr', text: 'sample diagnostic\n' }], message: `Exited with code ${code}.` } } })
  }, code)
}
test.beforeEach(async ({ page }) => {
  await installBackendFixture(page); await page.goto('/')
  await connectionEvent(page, { activeDeviceId: phone.id, devices: [phone] })
  await page.getByRole('navigation').getByRole('button', { name: 'Console', exact: true }).click()
})
test('runs only explicitly, pins selected transport, streams output and stops from another workspace', async ({ page }) => {
  await expect(page.getByRole('heading', { name: 'Console.' })).toBeVisible()
  await expect(page.getByRole('navigation').locator('.nav-entry').last().getByRole('button')).toHaveAccessibleName('Console')
  await expect(page.getByRole('navigation').locator('.nav-entry').nth(5).getByRole('button')).toHaveAccessibleName('Activity')
  await page.getByRole('button', { name: 'Device model', exact: true }).click()
  await expect(page.getByLabel('Console command', { exact: true })).toHaveValue('shell getprop ro.product.model')
  expect(await page.evaluate(() => window.backendTest.requests.some(r => r.type === 'console.run'))).toBe(false)
  await page.getByLabel('Console command', { exact: true }).press('Enter')
  expect(await page.evaluate(() => window.backendTest.requests.find(r => r.type === 'console.run'))).toEqual({ type: 'console.run', target: { id: 'phone', serial: phone.serial, transportId: '7' }, mode: 'adb', command: 'shell getprop ro.product.model', timeout: 120000 })
  await expect(page.getByRole('button', { name: 'Run command', exact: true })).toBeDisabled()
  await expect(page.getByLabel('Console device')).toBeDisabled()
  await page.evaluate(() => {
    const state = window.backendTest.snapshot.adbConsole!
    window.backendTest.emit({ type: 'adbConsole', state: { ...state, revision: state.revision + 1, run: { ...state.run!, output: [{ stream: 'stdout', text: 'streamed line\n' }] } } })
  })
  await expect(page.getByLabel('Command output', { exact: true })).toContainText('streamed line')
  await page.getByRole('navigation').getByRole('button', { name: 'Files', exact: true }).click()
  await page.getByRole('button', { name: 'Stop console command', exact: true }).click()
  await page.getByRole('navigation').getByRole('button', { name: 'Console', exact: true }).click()
  await expect(page.getByText('Stopped.', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Run command', exact: true })).toBeEnabled()
  await expect(page.getByLabel('Command output', { exact: true })).toContainText('streamed line')
})
