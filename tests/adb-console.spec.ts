test('Enter executes while Ctrl+Enter inserts at the cursor and replaces selected text', async ({ page }) => {
  await page.getByLabel('Console mode').selectOption('shell')
  const input = page.getByLabel('Console command', { exact: true })
  await input.fill('echo first echo second')
  await input.evaluate((el: HTMLTextAreaElement) => el.setSelectionRange(10, 11))
  await input.press('Control+Enter')
  await expect(input).toHaveValue('echo first\necho second')
  await expect.poll(() => input.evaluate((el: HTMLTextAreaElement) => [el.selectionStart, el.selectionEnd])).toEqual([11, 11])
  await input.press('End')
  await input.press('Control+Enter')
  await input.pressSequentially('echo third')
  await expect(input).toHaveValue('echo first\necho second\necho third')
  await input.dispatchEvent('keydown', { key: 'Enter', code: 'Enter', isComposing: true })
  await input.dispatchEvent('keydown', { key: 'Enter', code: 'Enter', repeat: true })
  expect(await page.evaluate(() => window.backendTest.requests.filter(r => r.type === 'console.run').length)).toBe(0)
  await input.press('Enter')
  await expect.poll(() => page.evaluate(() => window.backendTest.requests.filter(r => r.type === 'console.run').length)).toBe(1)
  expect(await page.evaluate(() => window.backendTest.requests.find(r => r.type === 'console.run'))).toMatchObject({ mode: 'shell', command: 'echo first\necho second\necho third' })
  await input.press('Enter')
  expect(await page.evaluate(() => window.backendTest.requests.filter(r => r.type === 'console.run').length)).toBe(1)
})

test('history fills without rerunning, restores draft, copies output and clears the session', async ({ page }) => {
  await page.getByLabel('Console mode').selectOption('shell')
  const input = page.getByLabel('Console command', { exact: true })
  await input.fill("echo 'hello world'")
  await page.getByRole('button', { name: 'Run command', exact: true }).click()
  await finish(page)
  await input.fill('unfinished draft')
  await input.press('ArrowUp'); await expect(input).toHaveValue("echo 'hello world'")
  await input.press('ArrowDown'); await expect(input).toHaveValue('unfinished draft')
  await page.getByLabel('Recent console commands').selectOption('0')
  await expect(input).toHaveValue("echo 'hello world'")
  expect(await page.evaluate(() => window.backendTest.requests.filter(r => r.type === 'console.run').length)).toBe(1)
  await page.getByRole('button', { name: 'Copy output', exact: true }).click()
  expect(await page.evaluate(() => window.backendTest.clipboardWrites.at(-1))).toContain('Android model\nsample diagnostic')
  await page.getByRole('button', { name: 'Clear session', exact: true }).click()
  await expect(page.getByText('Ready for a command', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Recent console commands')).toBeDisabled()
})
test('connection loss disables run and output remains tied to its original phone across navigation', async ({ page }) => {
  await page.getByLabel('Console command', { exact: true }).fill('shell id')
  await page.getByRole('button', { name: 'Run command', exact: true }).click()
  await finish(page, 1)
  await connectionEvent(page, { devices: [{ ...phone, status: 'disconnected' }], activeDeviceId: null })
  await expect(page.getByRole('button', { name: 'Run command', exact: true })).toBeDisabled()
  await expect(page.getByLabel('Console device')).toBeDisabled()
  await expect(page.getByLabel('Console device')).toContainText('No connected phones')
  await expect(page.getByText('No connected phones. Open Connection to connect a phone or check its authorization.', { exact: true })).toBeVisible()
  await expect(page.locator('.console-run-context')).toContainText('Test phone')
  await expect(page.locator('.console-result')).toHaveText('Exit 1')
  await page.screenshot({ path: 'test-results/console-no-device.png' })
  await page.getByRole('button', { name: 'Open Connection', exact: true }).click()
  await expect(page.getByRole('navigation').getByRole('button', { name: 'Connection', exact: true })).toHaveAttribute('aria-current', 'page')
  await page.getByRole('navigation').getByRole('button', { name: 'Console', exact: true }).click()
  await expect(page.getByLabel('Command output', { exact: true })).toContainText('Android model')
  await connectionEvent(page, { devices: [phone], activeDeviceId: null })
  await expect(page.getByLabel('Console device')).toBeEnabled()
  await page.getByLabel('Console device').selectOption(phone.id)
  await expect(page.getByRole('button', { name: 'Run command', exact: true })).toBeEnabled()
  expect(await page.evaluate(() => window.backendTest.requests.filter(r => r.type === 'console.run').length)).toBe(1)
})
test('console keeps controls and plain-text output usable at narrow widths and in dark mode', async ({ page }) => {
  await page.getByLabel('Console command', { exact: true }).fill('shell getprop')
  await page.getByRole('button', { name: 'Run command', exact: true }).click()
  await finish(page)
  await page.evaluate(() => {
    const state = window.backendTest.snapshot.adbConsole!
    window.backendTest.emit({ type: 'adbConsole', state: { ...state, revision: state.revision + 1, run: { ...state.run!, output: [{ stream: 'stdout', text: '<script>window.consoleInjected=true</script>\n' + 'model '.repeat(120) }] } } })
  })
  for (const width of [1440, 1000, 900]) {
    await page.setViewportSize({ width, height: 900 })
    await expect(page.getByRole('button', { name: 'Run command', exact: true })).toBeInViewport()
    expect(await page.locator('.workspace').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    expect(await page.evaluate(() => 'consoleInjected' in window)).toBe(false)
    await page.screenshot({ path: `test-results/adb-console-${width}.png` })
  }
  await page.getByRole('navigation').getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('button', { name: 'Theme Git Dark', exact: true }).click()
  await page.getByRole('navigation').getByRole('button', { name: 'Console', exact: true }).click()
  await page.screenshot({ path: 'test-results/adb-console-dark.png' })
  await page.getByRole('button', { name: 'Command list' }).click()
  const dialog = page.getByRole('dialog', { name: 'Command list' })
  await expect(dialog.getByLabel('Search commands')).toBeInViewport()
  await expect(dialog.getByRole('button', { name: 'Close', exact: true })).toBeInViewport()
  expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/console-command-list-dark-900.png' })
})
