function luminance(hex: string) {
  const rgb = [1, 3, 5].map(offset => {
    const channel = parseInt(hex.slice(offset, offset + 2), 16) / 255
    return channel <= 0.04045 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4
  })
  return rgb[0] * 0.2126 + rgb[1] * 0.7152 + rgb[2] * 0.0722
}
function contrast(a: string, b: string) {
  const values = [luminance(a), luminance(b)].sort((a, b) => b - a)
  return (values[0] + 0.05) / (values[1] + 0.05)
}
test('all palettes keep readable text and semantic badges', () => {
  for (const theme of [...themes, ...terminalThemes]) {
    const c = theme.colors
    for (const fg of ['text', 'muted']) for (const bg of ['bg', 'surface', 'surface-alt', 'sidebar']) {
      expect.soft(contrast(c[fg], c[bg]), `${theme.name}: ${fg}/${bg}`).toBeGreaterThanOrEqual(4.5)
    }
    for (const role of ['success', 'warning', 'error', 'info', 'violet', 'neutral']) {
      expect.soft(contrast(c[role], c[`${role}-bg`]), `${theme.name}: ${role}`).toBeGreaterThanOrEqual(4.5)
    }
    expect.soft(contrast(c['on-accent'], c.accent), `${theme.name}: button`).toBeGreaterThanOrEqual(4.5)
    expect.soft(contrast(c.accent, c.selected), `${theme.name}: selection`).toBeGreaterThanOrEqual(4.5)
  }
})
