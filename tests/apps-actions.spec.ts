  await page.evaluate(app => { Object.assign(window.backendTest.snapshot.apps, { apps: [app], userId: 10, profiles: [{ id: 0, name: 'Owner', managed: false, running: true }, { id: 10, name: 'Work', managed: true, running: true }] }) }, app)
