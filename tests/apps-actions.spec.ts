test('Disabled and disconnected apps cannot launch; removal result survives list refresh', async ({ page }) => {
  await page.evaluate(() => window.backendTest.emit({ type: 'apps', apps: { ...window.backendTest.snapshot.apps, apps: window.backendTest.snapshot.apps.apps.map(app => ({ ...app, enabled: false })) } }))
  const panel = page.getByRole('tabpanel')
  await expect(panel.getByRole('button', { name: 'Launch application' })).toBeDisabled()
  await panel.getByRole('button', { name: 'Enable application' }).click()
  expect(await page.evaluate(() => window.backendTest.requests.at(-1))).toMatchObject({ type: 'apps.action', action: 'enable', userId: 10 })
  await page.evaluate(() => {
    window.backendTest.emit({ type: 'appAction', state: { id: 'USB1', userId: 10, packageName: 'org.example.notes', action: 'uninstall', status: 'success', message: 'Application removed from this profile.' } })
    window.backendTest.emit({ type: 'apps', apps: { ...window.backendTest.snapshot.apps, apps: [] } })
  })
  await expect(panel).toContainText('Application removed from this profile.')
  await expect(panel.getByRole('button', { name: 'Uninstall from profile' })).toHaveCount(0)
})


test('inline cleanup selects categories for one app and includes cache in data', async ({ page }) => {
  const panel = page.getByRole('tabpanel')
  const before = await page.evaluate(() => window.backendTest.requests.length)
  await panel.getByRole('button', { name: 'Clear', exact: true }).click()
  const choices = panel.getByRole('group', { name: 'Cleanup categories' })
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(choices.getByRole('button', { name: 'Clear selected' })).toBeDisabled()
  await choices.getByRole('checkbox', { name: 'App data', exact: true }).check()
  await expect(choices.getByRole('checkbox', { name: /Cache/ })).toBeChecked()
  await expect(choices.getByRole('checkbox', { name: /Cache/ })).toBeDisabled()
  await expect(choices).toContainText('Included in app data')
  await choices.getByRole('checkbox', { name: 'App data', exact: true }).uncheck()
  await expect(choices.getByRole('checkbox', { name: /Cache/ })).not.toBeChecked()
  await expect(choices.getByRole('checkbox', { name: /Cache/ })).toBeEnabled()
  await panel.getByRole('button', { name: 'Clear', exact: true }).click()
  await expect(choices).toHaveCount(0)
  expect(await page.evaluate(() => window.backendTest.requests.length)).toBe(before)
  await panel.getByRole('button', { name: 'Clear', exact: true }).click()
  await choices.getByRole('button', { name: 'Select all', exact: true }).click()
  await page.screenshot({ path: 'test-results/inline-clear-single.png' })
  await choices.getByRole('button', { name: 'Clear selected' }).click()
  expect(await page.evaluate(() => window.backendTest.requests.at(-1))).toMatchObject({ type: 'apps.batchAction', plan: { action: 'clear-storage', id: 'USB1', userId: 10, packages: [app.packageName], cleanup: ['data', 'cache', 'obb', 'media'] } })
})
