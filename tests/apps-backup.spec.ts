test('backup format selects APK, APKS or Auto without changing the table selection', async ({ page }) => {
  await page.getByRole('checkbox', { name: 'Select all filtered applications', exact: true }).check()
  await page.getByRole('button', { name: 'Backup (2)', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Export applications' })
  const format = dialog.getByRole('combobox', { name: 'Export format' })
  await expect(format).toHaveValue('auto')
  for (const value of ['apk', 'apks', 'auto']) {
    await format.selectOption(value)
    if (value === 'apk') await expect(dialog).toContainText('base.apk is never saved separately')
    if (value === 'apks') await expect(dialog).toContainText('Single APK applications are skipped')
    await dialog.getByRole('button', { name: 'Export…', exact: true }).click()
    expect(await page.evaluate(() => window.backendTest.requests.at(-1))).toMatchObject({ type: 'apps.backup', selection: { format: value, packages: ['org.example.alpha', 'org.example.beta'] } })
    await dialog.getByRole('button', { name: 'Back', exact: true }).click()
  }
  await page.evaluate(() => window.backendTest.emit({ type: 'backup', state: { id: 'phone', userId: 0, name: 'user', format: 'apk', operation: 'backup', status: 'complete', message: 'Saved 1 applications. 1 skipped: different APK type.', completed: 2, total: 2, items: [{ packageName: 'org.example.alpha', label: 'Alpha', status: 'success' }, { packageName: 'org.example.beta', label: 'Beta', status: 'skipped', message: 'Skipped: split application.' }] } }))
  await dialog.getByRole('button', { name: 'View last result' }).click()
  await expect(dialog.locator('.backup-progress-summary')).toContainText('1 skipped')
  await expect(dialog.getByRole('list', { name: 'Backup results' })).toContainText('Skipped: split application.')
  await expect(dialog.getByRole('button', { name: 'Retry failed / cancelled…' })).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Backup (2)', exact: true })).toBeEnabled()
})

