import { test, expect } from '@playwright/test'
import { installBackendFixture, connectionEvent } from './backend-fixture'

test.beforeEach(async ({ page }) => {
  await installBackendFixture(page); await page.goto('/')
  await connectionEvent(page, { devices: [{ id: 'phone', serial: 'phone', name: 'Phone', method: 'USB', status: 'connected', android: '16', endpoint: 'phone', lastSeen: '', known: true, canDetach: false }], activeDeviceId: 'phone' })
  await page.getByRole('navigation').getByRole('button', { name: 'Apps', exact: true }).click()
})
test('Install is next to Backup, independent of checked table rows, and previews APK/APKS selected by default', async ({ page }) => {
  const controls = page.getByRole('group', { name: 'Application selection', exact: true })
  await expect(controls.getByRole('button', { name: 'Backup', exact: true })).toBeVisible()
  await controls.getByRole('button', { name: 'Install', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Install applications', exact: true })
  await expect(dialog.getByText('Phone · Owner · ID 0', { exact: false })).toBeVisible()
  await dialog.getByRole('button', { name: 'Choose files…' }).click()
  await expect(dialog.getByRole('checkbox', { name: 'Install Alpha.apk', exact: true })).toBeChecked()
  await expect(dialog.getByRole('checkbox', { name: 'Install Beta.apks', exact: true })).toBeChecked()
  await expect(dialog.getByRole('group', { name: 'What to restore' })).toHaveCount(0)
  await expect(dialog.getByText('Source device', { exact: true })).toHaveCount(0)
  await page.screenshot({ path: 'test-results/install-selection.png' })
  await dialog.getByRole('checkbox', { name: 'Install Beta.apks' }).uncheck()
  await dialog.getByRole('button', { name: 'Install selected (1)…' }).click()
  expect(await page.evaluate(() => window.backendTest.requests.at(-1))).toMatchObject({ type: 'apps.restoreBatch', plan: { packages: ['org.example.alpha'], components: ['apk'] } })
})
test('installation progress reopens the install window and Stop preserves the current operation', async ({ page }) => {
  await page.getByRole('button', { name: 'Install', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Install applications', exact: true })
  await dialog.getByRole('button', { name: 'Choose files…' }).click()
  await dialog.getByRole('button', { name: 'Install selected (2)…' }).click()
  await dialog.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Install', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Installing applications', exact: true }).click()
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: 'Stop after current application', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Stopping after current application…' })).toBeDisabled()
})
test('restore and installation previews remain separate, with installation help on click', async ({ page }) => {
  await page.getByRole('button', { name: 'Install', exact: true }).click()
  const install = page.getByRole('dialog', { name: 'Install applications', exact: true })
  await install.getByRole('button', { name: 'Choose files…' }).click()
  await expect(page.getByRole('dialog', { name: 'Installation help', exact: true })).not.toBeVisible()
  await install.getByRole('button', { name: 'Installation help', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Installation help', exact: true })).toBeVisible()
  await page.keyboard.press('Escape'); await install.getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('tab', { name: 'Actions', exact: true }).click()
  await page.getByRole('button', { name: 'Restore application', exact: true }).click()
  const restore = page.getByRole('dialog', { name: 'Restore application', exact: true })
  await expect(restore.getByText('Alpha.apk', { exact: true })).toHaveCount(0)
  await restore.getByRole('button', { name: 'Open backup…' }).click()
  await expect(restore.getByRole('checkbox', { name: 'Restore Alpha', exact: true })).toBeVisible()
})
