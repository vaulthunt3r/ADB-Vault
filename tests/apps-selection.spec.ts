test('all includes offscreen rows, clear includes hidden marks, and selection column stays visible', async ({ page }) => {
  await page.evaluate(seed => window.backendTest.emit({ type: 'apps', apps: { ...window.backendTest.snapshot.apps, apps: Array.from({ length: 100 }, (_, i) => ({ ...seed, label: `App ${i}`, packageName: `org.example.app${i}` })) } }), seed)
  await page.setViewportSize({ width: 1000, height: 680 })
  const all = page.getByRole('checkbox', { name: 'Select all filtered applications', exact: true })
  await all.check(); await expect(bar(page)).toContainText('Selected 100')
  const list = page.getByRole('region', { name: 'Application list', exact: true })
  await list.evaluate(el => { el.scrollLeft = el.scrollWidth; el.scrollTop = el.scrollHeight })
  await expect(all).toBeInViewport()
  await page.getByRole('searchbox', { name: 'Search applications', exact: true }).fill('org.example.app99')
  await expect(bar(page)).toContainText('99 hidden by filters')
  await page.getByRole('button', { name: 'Clear selection', exact: true }).click()
  await expect(bar(page)).toContainText('Selected 0')
  await all.check(); await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(bar(page)).toContainText('Selected 1')
  expect(await page.locator('main').evaluate(el => el.scrollHeight <= el.clientHeight && el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/apps-selection.png' })
})
