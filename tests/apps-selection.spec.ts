import { test, expect, type Page } from '@playwright/test'
import { installBackendFixture, connectionEvent } from './backend-fixture'
import type { AndroidApp } from '../electron/apps-protocol'

const seed: AndroidApp = { packageName: 'org.example.alpha', label: 'Alpha', userId: 0, uid: 10123, enabled: true, system: false, updatedSystemApp: false, debuggable: false, stopped: false, suspended: false, enabledState: 0, versionName: '1', versionCode: 1, sourceDir: '/data/app/base.apk', firstInstallTime: 0, lastUpdateTime: 0, targetSdk: 35, minSdk: 26, installer: null, iconPng: null, splitCount: 0 }
const navigation = (page: Page, name: string) => page.getByRole('navigation').getByRole('button', { name, exact: true })
const mark = (page: Page, name: string) => page.getByRole('checkbox', { name: `Select ${name} (org.example.${name.toLowerCase()})`, exact: true })
const bar = (page: Page) => page.getByRole('group', { name: 'Application selection', exact: true })
test.beforeEach(async ({ page }) => {
  await installBackendFixture(page); await page.goto('/')
  await connectionEvent(page, { devices: [{ id: 'phone', serial: 'phone', name: 'Phone', method: 'USB', status: 'connected', android: '16', endpoint: 'phone', lastSeen: '', known: true, canDetach: false }], activeDeviceId: 'phone' })
  await page.evaluate(seed => { window.backendTest.snapshot.apps.apps = ['Alpha', 'Beta', 'Gamma'].map(label => ({ ...seed, label, packageName: `org.example.${label.toLowerCase()}` })) }, seed)
  await navigation(page, 'Apps').click()
})

test('inline selection controls keep the table stable and selection independent of Details and Actions', async ({ page }) => {
  await expect(bar(page)).toContainText('Selected 0')
  const list = page.getByRole('region', { name: 'Application list', exact: true })
  const originalTop = await list.evaluate(el => el.getBoundingClientRect().top)
  await expect(page.getByRole('button', { name: 'Clear selection', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Details for Alpha', exact: true }).click()
  await mark(page, 'Beta').check()
  await expect(bar(page)).toContainText('Selected 1')
  expect(await list.evaluate(el => el.getBoundingClientRect().top)).toBe(originalTop)
  await expect(page.getByRole('button', { name: 'Details for Alpha', exact: true })).toHaveAttribute('aria-pressed', 'true')
  const all = page.getByRole('checkbox', { name: 'Select all filtered applications', exact: true })
  await expect(all).toBeChecked({ indeterminate: true })
  await page.getByRole('searchbox', { name: 'Search applications', exact: true }).fill('Alpha')
  await expect(bar(page)).toContainText('1 hidden by filters')
  await all.check()
  await expect(bar(page)).toContainText('Selected 2')
  await all.uncheck()
  await expect(bar(page)).toContainText('Selected 1')
  await page.getByRole('searchbox', { name: 'Search applications', exact: true }).fill('missing')
  await expect(all).toBeDisabled()
  await expect(bar(page)).toContainText('1 hidden by filters')
  await expect(page.getByRole('button', { name: 'Review selection', exact: true })).toHaveCount(0)
  await page.getByRole('tab', { name: 'Actions', exact: true }).click()
  await expect(page.getByRole('tabpanel')).toContainText('org.example.alpha')
  expect(await page.evaluate(() => window.backendTest.requests.some(r => r.type === 'apps.action'))).toBe(false)
  await page.getByRole('button', { name: 'Clear selection', exact: true }).click()
  await expect(bar(page)).toContainText('Selected 0')
  expect(await list.evaluate(el => el.getBoundingClientRect().top)).toBe(originalTop)
  await expect(page.getByRole('button', { name: 'Clear selection', exact: true })).toBeDisabled()
})

test('range selection works with mouse and keyboard without opening Details', async ({ page }) => {
  await mark(page, 'Alpha').check()
  await mark(page, 'Gamma').click({ modifiers: ['Shift'] })
  await expect(bar(page)).toContainText('Selected 3')
  await page.getByRole('button', { name: 'Clear selection', exact: true }).click()
  await mark(page, 'Alpha').focus(); await page.keyboard.press('Space')
  await mark(page, 'Gamma').focus(); await page.keyboard.press('Shift+Space')
  await expect(mark(page, 'Beta')).toBeChecked()
  await expect(bar(page)).toContainText('Selected 3')
  await page.keyboard.press('Enter')
  await mark(page, 'Beta').dblclick()
  await expect(page.getByRole('region', { name: 'Application details', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Details for Alpha', exact: true }).dblclick()
  await expect(page.getByRole('region', { name: 'Application details', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Back to Apps', exact: true }).click()
  await expect(bar(page)).toContainText('Selected 3')
})

test('selection checkboxes fit within the original default table width', async ({ page }) => {
  await page.evaluate(seed => window.backendTest.emit({ type: 'apps', apps: { ...window.backendTest.snapshot.apps, apps: Array.from({ length: 100 }, (_, i) => ({ ...seed, label: `Application ${i}`, packageName: `org.example.application${i}` })) } }), seed)
  const list = page.getByRole('region', { name: 'Application list', exact: true })
  const width = await list.evaluate(el => el.clientWidth)
  await page.setViewportSize({ width: 1440 + 800 - width, height: 940 })
  await expect.poll(() => list.evaluate(el => el.clientWidth)).toBe(800)
  expect(await list.evaluate(el => el.scrollHeight > el.clientHeight)).toBe(true)
  expect(await list.evaluate(el => el.scrollWidth)).toBe(800)
  await page.getByRole('checkbox', { name: 'Select all filtered applications', exact: true }).check()
  expect(await list.evaluate(el => el.scrollWidth)).toBe(800)
  await expect(page.getByRole('columnheader', { name: 'STATUS', exact: true })).toBeInViewport()
  // Comfortable padding must not force the default columns to their preferred pixel widths.
  const viewport = page.viewportSize()!
  await page.setViewportSize({ ...viewport, width: viewport.width - 60 })
  await expect.poll(() => list.evaluate(el => el.clientWidth)).toBe(740)
  expect(await list.evaluate(el => el.scrollWidth)).toBe(740)
  await expect(page.getByRole('columnheader', { name: 'STATUS', exact: true })).toBeInViewport()
  await page.screenshot({ path: 'test-results/apps-comfortable-fluid.png' })
  await page.setViewportSize(viewport)
  await page.getByRole('button', { name: 'Visible columns', exact: true }).click()
  await page.getByRole('dialog', { name: 'Visible columns', exact: true }).getByRole('checkbox', { name: 'Package name', exact: true }).check()
  await page.keyboard.press('Escape')
  expect(await list.evaluate(el => el.scrollWidth > el.clientWidth)).toBe(true)
  expect(await page.locator('main').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
})

test('Status badges preserve concurrent states, use saved colors and stack centrally', async ({ page }) => {
  await page.evaluate(() => window.backendTest.emit({ type: 'apps', apps: { ...window.backendTest.snapshot.apps, apps: window.backendTest.snapshot.apps.apps.map((app, i) => ({ ...app, enabled: i !== 1, stopped: i > 0, suspended: i === 1 })) } }))
  const row = (name: string) => page.getByRole('row').filter({ has: page.getByRole('button', { name: `Details for ${name}`, exact: true }) })
  await expect(row('Alpha').getByText('Enabled', { exact: true })).toBeVisible()
  await expect(row('Gamma').getByText('Enabled', { exact: true })).toHaveCount(0)
  await expect(row('Gamma').getByText('Stopped', { exact: true })).toHaveAttribute('title', /not a check for running processes/)
  for (const name of ['Disabled', 'Stopped', 'Suspended']) await expect(row('Beta').getByText(name, { exact: true })).toBeVisible()
  await navigation(page, 'Settings').click()
  await page.getByRole('group', { name: 'Settings categories' }).getByRole('button', { name: 'Badges', exact: true }).click()
  await page.getByLabel('Color Disabled', { exact: true }).fill('#c9253b')
  await page.getByLabel('Color Stopped', { exact: true }).fill('#9a480c')
  await page.getByLabel('Color Suspended', { exact: true }).fill('#8033aa')
  await navigation(page, 'Apps').click()
  await expect(row('Beta').getByText('Disabled', { exact: true })).toHaveCSS('background-color', 'rgb(201, 37, 59)')
  await expect(row('Beta').getByText('Stopped', { exact: true })).toHaveCSS('background-color', 'rgb(154, 72, 12)')
  await expect(row('Beta').getByText('Suspended', { exact: true })).toHaveCSS('background-color', 'rgb(128, 51, 170)')
  const positions = await row('Beta').locator('.app-info-badge').evaluateAll(icons => icons.map(icon => icon.getBoundingClientRect().top))
  expect(new Set(positions).size).toBe(3)
  const centered = await row('Beta').locator('.apps-package-states').evaluate(el => {
    const cell = el.getBoundingClientRect()
    return Array.from(el.children).every(child => {
      const badge = child.getBoundingClientRect()
      return Math.abs((badge.left + badge.right) / 2 - (cell.left + cell.right) / 2) < 1
    })
  })
  expect(centered).toBe(true)
  await expect(page.getByRole('columnheader', { name: 'STATUS', exact: true })).toHaveCSS('text-align', 'center')
  expect(await row('Beta').locator('.apps-package-states').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/apps-status-badges.png' })
})

test('selection survives sort, navigation and refresh but prunes removed apps and excludes new ones', async ({ page }) => {
  await page.getByRole('checkbox', { name: 'Select all filtered applications', exact: true }).check()
  await page.getByRole('button', { name: 'Sort applications', exact: true }).click()
  await page.getByRole('radio', { name: 'Z → A', exact: true }).check(); await page.keyboard.press('Escape')
  await expect(bar(page)).toContainText('Selected 3')
  await navigation(page, 'Settings').click()
  await page.evaluate(seed => {
    const apps = window.backendTest.snapshot.apps
    window.backendTest.emit({ type: 'apps', apps: { ...apps, status: 'loading', apps: [] } })
    window.backendTest.emit({ type: 'apps', apps: { ...apps, status: 'error', apps: [], error: 'Test read failure' } })
    window.backendTest.emit({ type: 'apps', apps: { ...apps, status: 'ready', apps: [apps.apps[0], apps.apps[2], { ...seed, packageName: 'org.example.delta', label: 'Delta' }] } })
  }, seed)
  await navigation(page, 'Apps').click()
  await expect(bar(page)).toContainText('Selected 2')
  await expect(mark(page, 'Alpha')).toBeChecked(); await expect(mark(page, 'Gamma')).toBeChecked()
  await expect(mark(page, 'Delta')).not.toBeChecked()
  const snapshot = await page.evaluate(() => window.backendTest.snapshot)
  await page.reload()
  await connectionEvent(page, snapshot.connection)
  await page.evaluate(apps => window.backendTest.emit({ type: 'apps', apps }), snapshot.apps)
  await navigation(page, 'Apps').click()
  await expect(bar(page)).toContainText('Selected 0')
})

