import { test, expect, type Page } from '@playwright/test'
import { installBackendFixture, connectionEvent } from './backend-fixture'
import type { AndroidApp } from '../electron/apps-protocol'

const seed: AndroidApp = { packageName: 'org.example.alpha', label: 'Alpha', userId: 0, uid: 10123, enabled: true, system: false, updatedSystemApp: false, debuggable: false, stopped: false, suspended: false, enabledState: 0, versionName: '1', versionCode: 1, sourceDir: '/data/app/base.apk', firstInstallTime: 0, lastUpdateTime: 0, targetSdk: 35, minSdk: 26, installer: null, iconPng: null, splitCount: 0 }
const navigate = (page: Page, name: string) => page.getByRole('navigation').getByRole('button', { name, exact: true }).click()
test.beforeEach(async ({ page }) => { await installBackendFixture(page) })

test('corner style unifies controls, cards, overflow and dialogs without changing toolbar layout', async ({ page }) => {
  test.setTimeout(90_000)
  await page.goto('/')
  await connectionEvent(page, { devices: [{ id: 'phone', serial: 'phone', name: 'Phone', method: 'USB', status: 'connected', android: '16', endpoint: 'phone', lastSeen: '', known: true, canDetach: false }], activeDeviceId: 'phone' })
  await page.evaluate(seed => { window.backendTest.snapshot.apps.apps = [seed] }, seed)
  const toolbar = page.getByLabel('Workspace toolbar')
  const initialHeight = (await toolbar.boundingBox())!.height
  for (const [style, radius] of [['Rounded', '8px'], ['Square', '0px']]) {
    await navigate(page, 'Settings')
    await page.getByRole('radio', { name: style, exact: true }).check()
    await expect(page.locator('.toolbar-settings')).toHaveCSS('border-top-left-radius', radius)
    await expect(toolbar.getByRole('button', { name: 'Select phone', exact: true })).toHaveCSS('border-radius', radius)
    await toolbar.getByRole('button', { name: 'More toolbar actions' }).click()
    await expect(page.getByRole('dialog', { name: 'Toolbar actions', exact: true })).toHaveCSS('border-radius', radius)
    await page.keyboard.press('Escape')
    await navigate(page, 'Components')
    await expect(page.locator('.component-table')).toHaveCSS('border-radius', radius)
    await expect(page.locator('.component-search')).toHaveCSS('border-radius', radius)
    await navigate(page, 'Apps')
    await expect(page.locator('.apps-table-scroll')).toBeVisible()
    await expect(page.locator('.apps-live-section .button').first()).toHaveCSS('border-radius', radius)
    await expect(page.locator('.apps-profile-picker select').first()).toHaveCSS('border-radius', radius)
    await page.screenshot({ path: `test-results/corners-${style.toLowerCase()}-apps.png` })
    await page.getByRole('checkbox', { name: 'Select all filtered applications', exact: true }).check()
    await page.getByRole('button', { name: 'Backup (1)', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'Export applications' })
    await expect(dialog).toHaveCSS('border-radius', radius)
    await expect(dialog.locator('.backup-form input').first()).toHaveCSS('border-radius', radius)
    await expect(dialog.locator('.export-part').first()).toHaveCSS('border-radius', radius)
    await expect(dialog.getByRole('button', { name: 'Export…', exact: true })).toHaveCSS('border-radius', radius)
    await dialog.getByRole('button', { name: 'Close', exact: true }).click()
    const collected = await page.evaluate(() => window.backendTest.snapshot.apps)
    await page.evaluate(() => window.backendTest.emit({ type: 'apps', apps: { ...window.backendTest.snapshot.apps, deviceId: 'phone', status: 'loading', message: 'Reading applications', progress: { completed: 148, total: 520 } } }))
    await expect(toolbar.locator('.operation-chip')).toHaveCSS('border-radius', radius)
    await toolbar.getByRole('button', { name: 'Cancel collection', exact: true }).click()
    // The fixture clears the collection on cancellation; restore it for the next style.
    await page.evaluate(apps => window.backendTest.emit({ type: 'apps', apps }), collected)
    await navigate(page, 'Files')
    await expect(page.locator('.fm-pane').first()).toHaveCSS('border-radius', radius)
    expect((await toolbar.boundingBox())!.height).toBe(initialHeight)
    expect(initialHeight).toBe(46)
    await expect(page.locator('.nav-status-mark').first()).toHaveCSS('border-radius', '50%')
  }
})

test('corner style persists independently of color and Zen, restores after Zero Cool and normalizes legacy preferences', async ({ page }) => {
  test.setTimeout(90_000)
  await page.goto('/')
  await navigate(page, 'Settings')
  await expect(page.getByRole('radio', { name: 'Rounded', exact: true })).toBeChecked()
  await page.getByRole('radio', { name: 'Square', exact: true }).check()
  await page.getByRole('button', { name: 'Theme Git Dark', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Zen mode', exact: true }).check()
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-corner-style', 'square')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'git-dark')
  await expect(page.locator('html')).toHaveAttribute('data-zen-mode', 'true')
  await expect(page.locator('.component-table')).toHaveCSS('border-radius', '0px')
  await navigate(page, 'Settings')
  await expect(page.getByRole('radio', { name: 'Square', exact: true })).toBeChecked()
  await page.getByRole('radio', { name: 'Rounded', exact: true }).check()
  const toggle = page.getByRole('button', { name: 'Terminal mode', exact: true })
  const device = page.getByRole('button', { name: 'Select phone', exact: true })
  await toggle.dblclick()
  await expect(device).toHaveCSS('border-radius', '0px')
  await expect(page.getByRole('radio', { name: 'Rounded', exact: true })).toBeChecked()
  await expect(page.getByRole('group', { name: 'Corner style', exact: true })).toContainText('Zero Cool uses square corners')
  await toggle.dblclick()
  await expect(device).toHaveCSS('border-radius', '8px')
  await page.reload()
  await expect(device).toHaveCSS('border-radius', '8px')
  for (const cornerStyle of [undefined, 'invalid']) {
    await page.evaluate(cornerStyle => localStorage.setItem('adb-vault-appearance', JSON.stringify({ state: { themeId: 'git-dark', cornerStyle }, version: 1 })), cornerStyle)
    await page.reload()
    await expect(page.locator('html')).toHaveAttribute('data-corner-style', 'rounded')
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'git-dark')
  }
})
