test('pairing and manual connection send their exact, separate ports', async ({ page }) => {
  await page.getByLabel('Pairing IP address').fill('192.168.1.9'); await page.getByLabel('Pairing port').fill('37123'); await page.getByLabel('Pairing code', { exact: true }).fill('123456')
  await page.getByRole('button', { name: 'Pair device', exact: true }).click()
  expect(await page.evaluate(() => window.backendTest.requests.find(r => r.type === 'connection.pair'))).toEqual({ type: 'connection.pair', host: '192.168.1.9', port: '37123', code: '123456' })
  await expect(page.getByLabel('Pairing code', { exact: true })).toHaveValue('')
  await expect(page.getByText('No active device', { exact: true })).toBeVisible()
  await page.getByLabel('Connection port').fill('39876'); await page.getByRole('button', { name: 'Connect address' }).click()
  expect(await page.evaluate(() => window.backendTest.requests.find(r => r.type === 'connection.connect'))).toEqual({ type: 'connection.connect', host: '192.168.1.9', port: '39876' })
})
