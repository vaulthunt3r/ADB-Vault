test('connection errors expire across navigation, stay dismissed on polling and reappear for a new failure', async ({ page }) => {
  await page.clock.install()
  const error = 'Cannot connect: test port refused.'
  await page.evaluate(text => window.backendTest.emit({ type: 'activity', text, tone: 'warning' }), error)
  await connectionEvent(page, { error })
  await expect(page.getByRole('alert')).toContainText(error)
  await page.clock.fastForward(5000)
  await connectionEvent(page, { scanning: true })
  await connectionEvent(page, { scanning: false })
  await expect(page.getByRole('alert')).toBeVisible()
  await page.getByRole('navigation').getByRole('button', { name: 'Settings', exact: true }).click()
  await page.clock.fastForward(3100)
  await page.getByRole('navigation').getByRole('button', { name: 'Connection', exact: true }).click()
  await connectionEvent(page, { scanning: false })
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.getByRole('navigation').getByRole('button', { name: 'Activity', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Session events' })).toContainText(error)
  await page.getByRole('navigation').getByRole('button', { name: 'Connection', exact: true }).click()
  await connectionEvent(page, { error: null, busy: true })
  await connectionEvent(page, { error, busy: false })
  await expect(page.getByRole('alert')).toContainText(error)
  await page.getByRole('button', { name: 'Dismiss connection error' }).click()
  await connectionEvent(page, { scanning: false })
  await expect(page.getByRole('alert')).toHaveCount(0)
  await connectionEvent(page, { error: 'Another connection error.' })
  await page.clock.fastForward(7900)
  await expect(page.getByRole('alert')).toBeVisible()
  await page.clock.fastForward(101)
  await expect(page.getByRole('alert')).toHaveCount(0)
})
test('Known devices scrolls independently and inactive entries can be forgotten', async ({ page }) => {
  const devices = Array.from({ length: 20 }, (_, i) => ({ ...phone, id: `USB${i}`, serial: `USB${i}`, endpoint: `USB${i}`, name: `Phone ${i}`, status: i === 0 ? 'connected' as const : 'disconnected' as const }))
  await connectionEvent(page, { devices, activeDeviceId: 'USB0' })
  await page.setViewportSize({ width: 1000, height: 800 })
  const list = page.getByRole('region', { name: 'Known devices list' })
  await expect(page.getByRole('button', { name: 'Forget Phone 0', exact: true })).toHaveCount(0)
  expect(await list.evaluate(el => el.scrollHeight > el.clientHeight && el.clientHeight <= 360)).toBe(true)
  await list.focus(); await list.press('End')
  await expect.poll(() => list.evaluate(el => el.scrollTop)).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Forget Phone 19', exact: true }).click()
  const confirmation = page.getByRole('dialog', { name: 'Forget Phone 19?' })
  await expect(confirmation).toBeVisible()
  await expect(confirmation).toContainText('USB · USB19')
  await expect(confirmation).toContainText('Phone pairing and USB debugging authorization will remain unchanged.')
  await expect(confirmation.getByRole('button', { name: 'Cancel', exact: true })).toBeFocused()
  expect(await page.evaluate(() => window.backendTest.requests.some(r => r.type === 'connection.forget'))).toBe(false)
  await confirmation.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Forget Phone 19', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Forget Phone 19', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(confirmation).toHaveCount(0)
  expect(await page.evaluate(() => window.backendTest.requests.some(r => r.type === 'connection.forget'))).toBe(false)
  await page.getByRole('button', { name: 'Forget Phone 19', exact: true }).click()
  await page.screenshot({ path: 'test-results/forget-confirmation.png' })
  await confirmation.getByRole('button', { name: 'Forget device', exact: true }).click()
  expect(await page.evaluate(() => window.backendTest.requests.at(-1))).toEqual({ type: 'connection.forget', id: 'USB19' })
  await expect(confirmation).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Select Phone 19', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Select Phone 0', exact: true })).toHaveCount(1)
  await page.screenshot({ path: 'test-results/known-devices-scroll.png' })
})

test('Forget confirmation prevents removal if the phone reconnects while the dialog is open', async ({ page }) => {
  await connectionEvent(page, { devices: [{ ...phone, status: 'disconnected' }] })
  await page.getByRole('button', { name: 'Forget Test phone', exact: true }).click()
  await connectionEvent(page, { devices: [phone], activeDeviceId: phone.id })
  const confirmation = page.getByRole('dialog')
  await expect(confirmation.getByRole('button', { name: 'Forget device', exact: true })).toBeDisabled()
  await expect(confirmation).toContainText('disconnect it first')
  await confirmation.getByRole('button', { name: 'Cancel', exact: true }).click()
  expect(await page.evaluate(() => window.backendTest.requests.some(r => r.type === 'connection.forget'))).toBe(false)
})
