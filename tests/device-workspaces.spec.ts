import { test, expect } from '@playwright/test'
import { connectionEvent, installBackendFixture } from './backend-fixture'
import type { DeviceRecord } from '../electron/contracts'
const phone: DeviceRecord = { id: 'USB1', serial: 'USB1', name: 'Test phone', android: '15', status: 'connected', method: 'USB', endpoint: 'USB1', lastSeen: new Date().toISOString(), known: true, canDetach: false }
test.beforeEach(async ({ page }) => { await installBackendFixture(page); await page.goto('/'); await page.getByRole('navigation').getByRole('button', { name: 'Connection', exact: true }).click() })

test('devices are selected in Connection without a duplicate toolbar selector', async ({ page }) => {
  await connectionEvent(page, { devices: [phone], activeDeviceId: phone.id })
  await expect(page.getByRole('navigation').getByRole('button', { name: 'Connection', exact: true })).toHaveAccessibleDescription(/Connected · USB.*Device: Test phone/s)
  await expect(page.getByRole('combobox', { name: 'Active device' })).toHaveCount(0)
  const second = { ...phone, id: 'USB2', serial: 'USB2', name: 'Second phone' }
  await connectionEvent(page, { devices: [phone, second], activeDeviceId: phone.id })
  await page.getByRole('button', { name: 'Select Second phone', exact: true }).click()
  expect(await page.evaluate(() => window.backendTest.requests.filter(r => r.type === 'connection.select').at(-1))).toEqual({ type: 'connection.select', id: second.id })
  await connectionEvent(page, { devices: [{ ...phone, status: 'disconnected' }, second], activeDeviceId: second.id })
  await expect(page.getByRole('navigation').getByRole('button', { name: 'Connection', exact: true })).toHaveAccessibleDescription(/Connected · USB.*Device: Second phone/s)
  await expect(page.getByRole('combobox', { name: 'Active device' })).toHaveCount(0)
})
