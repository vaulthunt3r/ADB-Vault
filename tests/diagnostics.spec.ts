test('Activity is a workspace with filters, full messages, export and only two inspector tabs', async ({ page }) => {
  await connectionEvent(page, { devices: [{ id: 'USB1', serial: 'USB1', name: 'Test phone', android: '16', status: 'connected', method: 'USB', endpoint: 'USB1', lastSeen: '', known: true, canDetach: false }], activeDeviceId: 'USB1' })
  await page.evaluate(() => {
    window.backendTest.emit({ type: 'activity', source: 'components', tone: 'success', text: 'ADB verified.' })
    window.backendTest.emit({ type: 'activity', source: 'connection', device: 'USB1', tone: 'warning', text: 'Connection refused: test diagnostic.' })
    window.backendTest.emit({ type: 'activity', source: 'apps', device: 'USB1', tone: 'success', text: 'Read applications.' })
  })
  await page.getByRole('navigation').getByRole('button', { name: 'Activity', exact: true }).click()
  await expect(page.getByRole('tab')).toHaveCount(2)
  await expect(page.getByRole('tab', { name: 'Activity' })).toHaveCount(0)
  await expect(page.getByRole('row')).toHaveCount(4)
  const history = page.getByRole('region', { name: 'Session events' })
  await expect(history.getByRole('columnheader', { name: 'Workspace', exact: true })).toBeVisible()
  await expect(history.getByRole('columnheader', { name: 'Device', exact: true })).toBeVisible()
  await expect(history.getByRole('cell', { name: 'Test phone', exact: true })).toHaveCount(2)
  await expect(history.locator('.activity-workspace svg')).toHaveCount(3)
  await connectionEvent(page, { devices: [], activeDeviceId: null })
  await expect(history.getByRole('cell', { name: 'Test phone', exact: true })).toHaveCount(2)
  await page.getByLabel('Event workspace').selectOption('connection')
  await page.getByLabel('Event result').selectOption('warning')
  await page.getByLabel('Search activity').fill('USB1')
  await expect(page.getByRole('row')).toHaveCount(2)
  await page.getByRole('button', { name: 'Event: Connection refused: test diagnostic.' }).click()
  await expect(page.getByRole('tabpanel')).toContainText('Connection refused: test diagnostic.')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export shown' }).click()
  const file = await download
  const text = await readFile((await file.path())!, 'utf8')
  expect(text).toContain('Connection refused'); expect(text).not.toContain('Read applications.')
  expect(text).toContain('Test phone'); expect(text).toContain('Device identifier: USB1')
  await page.getByRole('tab', { name: 'Details', exact: true }).focus()
  await page.keyboard.press('End'); await expect(page.getByRole('tab', { name: 'Actions', exact: true })).toBeFocused()
  await page.keyboard.press('ArrowRight'); await expect(page.getByRole('tab', { name: 'Details', exact: true })).toBeFocused()
  await page.setViewportSize({ width: 1000, height: 680 })
  expect(await page.locator('main').evaluate(el => el.scrollWidth <= el.clientWidth && el.scrollHeight <= el.clientHeight)).toBe(true)
  await page.screenshot({ path: 'test-results/activity-workspace.png' })
})
test('Connection reads firmware only for connected devices, reuses it and supports explicit refresh', async ({ page }) => {
  const phone = { id: 'USB1', serial: 'USB1', name: 'Test phone', android: '16', status: 'connected' as const, method: 'USB' as const, endpoint: 'USB1', lastSeen: new Date().toISOString(), known: true, canDetach: false }
  await connectionEvent(page, { devices: [phone], activeDeviceId: phone.id })
  await page.getByRole('navigation').getByRole('button', { name: 'Connection', exact: true }).click()
  const panel = page.getByLabel('Device and firmware')
  await expect(panel).toContainText('Test vendor')
  await expect(panel).toContainText('2026-09-01')
  await expect(panel).toContainText('arm64-v8a')
  const count = () => page.evaluate(() => window.backendTest.requests.filter(r => r.type === 'connection.info').length)
  expect(await count()).toBe(1)
  await connectionEvent(page, { scanning: true }); await connectionEvent(page, { scanning: false })
  await page.getByRole('navigation').getByRole('button', { name: 'Components', exact: true }).click()
  await page.getByRole('navigation').getByRole('button', { name: 'Connection', exact: true }).click()
  expect(await count()).toBe(1)
  await expect(panel.getByRole('button', { name: 'Refresh' })).toHaveCount(0)
  await page.getByRole('tab', { name: 'Actions', exact: true }).click()
  await page.getByRole('button', { name: 'Refresh device information', exact: true }).click(); expect(await count()).toBe(2)
  await page.getByRole('tab', { name: 'Details', exact: true }).click()
  await panel.scrollIntoViewIfNeeded(); await page.screenshot({ path: 'test-results/device-firmware.png' })
  await connectionEvent(page, { devices: [{ ...phone, status: 'unauthorized' }], activeDeviceId: null })
  await page.getByRole('tab', { name: 'Actions', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Refresh device information', exact: true })).toBeDisabled()
  expect(await count()).toBe(2)
})

test('switching connection tabs sends no device actions and background reads do not block unrelated controls', async ({ page }) => {
  const phone = { id: 'USB1', serial: 'USB1', transportId: '7', name: 'Test phone', android: '16', status: 'connected' as const, method: 'USB' as const, endpoint: 'USB1', lastSeen: new Date().toISOString(), known: true, canDetach: false }
  await connectionEvent(page, { devices: [phone], activeDeviceId: phone.id })
  await page.getByRole('navigation').getByRole('button', { name: 'Connection', exact: true }).click()
  await expect(page.getByLabel('Device and firmware')).toContainText('Test vendor')
  await page.evaluate(() => {
    const state = window.backendTest.snapshot.connection
    window.backendTest.emit({ type: 'connection', connection: { ...state, devices: state.devices.map(d => ({ ...d, root: { status: 'checking', message: 'Passive detection', checkedAt: null }, info: { status: 'loading', fields: {}, collectedAt: null } })) } })
    window.backendTest.emit({ type: 'components', components: window.backendTest.snapshot.components.map(c => c.id === 'scrcpy' ? { ...c, status: 'Installed', location: 'C:\\scrcpy' } : c) })
  })
  const count = await page.evaluate(() => window.backendTest.requests.length)
  for (let i = 0; i < 3; i++) {
    await page.getByRole('tab', { name: 'Actions', exact: true }).click()
    for (const name of ['Restart', 'Power off', 'Mirror screen', 'Screenshot', 'Wake screen', 'Sleep screen']) await expect(page.getByRole('tabpanel').getByRole('button', { name, exact: true })).toBeEnabled()
    await expect(page.getByRole('button', { name: 'Checking root access…', exact: true })).toBeDisabled()
    await expect(page.getByRole('button', { name: 'Checking root access…', exact: true }).locator('.lattice-loader')).toBeVisible()
    await expect(page.getByRole('button', { name: 'Reading device information…', exact: true })).toBeDisabled()
    await page.getByRole('tab', { name: 'Details', exact: true }).click()
  }
  expect(await page.evaluate(() => window.backendTest.requests.length)).toBe(count)
  expect(await page.evaluate(() => window.backendTest.requests.filter(r => ['connection.power', 'connection.screen', 'connection.reconnect', 'connection.disconnect'].includes(r.type)))).toHaveLength(0)
})
