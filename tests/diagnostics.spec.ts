test('Connection badges describe phone root independently of permission, with checks in Actions', async ({ page }) => {
  const phone = { id: 'USB1', serial: 'USB1', name: 'Test phone', android: '13', status: 'connected' as const, method: 'USB' as const, endpoint: 'USB1', lastSeen: new Date().toISOString(), known: true, canDetach: false }
  await connectionEvent(page, { devices: [phone], activeDeviceId: phone.id })
  await page.getByRole('navigation').getByRole('button', { name: 'Connection', exact: true }).click()
  const root = page.getByLabel('Root on device')
  await expect(root).toHaveText('Rooted')
  await expect(root.locator('..')).toContainText('Connected')
  expect(await page.evaluate(() => window.backendTest.requests.some(r => r.type === 'connection.root' && r.requestAccess))).toBe(false)
  await expect(page.getByRole('button', { name: 'Check root access', exact: true })).toHaveCount(0)
  await page.screenshot({ path: 'test-results/device-root-details.png' })
  await page.getByRole('tab', { name: 'Actions', exact: true }).click()
  await page.getByRole('button', { name: 'Check root access', exact: true }).click()
  await expect(root).toHaveText('Rooted')
  await expect(page.getByRole('tabpanel')).toContainText('ADB root access: Granted')
  await expect(page.getByRole('button', { name: 'Refresh device information', exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/device-root-actions.png' })
  expect(await page.evaluate(() => window.backendTest.snapshot.apps.options.root)).toBeUndefined()
  await page.getByRole('tab', { name: 'Details', exact: true }).click()
  await connectionEvent(page, { devices: [{ ...phone, root: { status: 'denied', method: 'su', checkedAt: null, message: 'Allow Shell/ADB in the root manager.' } }] })
  await expect(root).toHaveText('Rooted')
  await expect(page.getByRole('tabpanel')).toContainText('ADB root access: Not granted')
  await connectionEvent(page, { devices: [{ ...phone, root: { status: 'error', method: 'su', checkedAt: null, message: 'Root access check timed out.' } }] })
  await expect(root).toHaveText('Rooted')
  await connectionEvent(page, { devices: [{ ...phone, root: { status: 'error', checkedAt: null, message: 'Could not check root.' } }] })
  await expect(root).toHaveText('Root unknown')
  await connectionEvent(page, { devices: [{ ...phone, root: { status: 'not-detected', checkedAt: null, message: 'Root not detected.' } }] })
  await expect(root).toHaveText('Root not detected')
  await connectionEvent(page, { devices: [{ ...phone, status: 'disconnected' }] })
  await expect(root).toHaveText('Root unknown')
  await page.getByRole('tab', { name: 'Actions', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Check root access', exact: true })).toBeDisabled()
})
