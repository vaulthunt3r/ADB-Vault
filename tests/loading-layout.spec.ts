import { test, expect } from '@playwright/test'
import { installBackendFixture, connectionEvent } from './backend-fixture'

test.beforeEach(async ({ page }) => { await installBackendFixture(page); await page.goto('/') })
for (const density of ['comfortable', 'compact']) test(`component check keeps row positions, filtered rows and summary stable: ${density}`, async ({ page }) => {
  await page.evaluate(density => localStorage.setItem('adb-vault-appearance', JSON.stringify({ state: { density }, version: 1 })), density)
  await page.reload()
  await page.evaluate(() => { const s = window.backendTest; s.emit({ type: 'components', components: s.snapshot.components.map(c => c.id === 'driver' ? { ...c, status: 'Manual action required' } : c) }) })
  const row = page.getByTestId('component-driver'), table = page.getByRole('table', { name: 'Dependencies and components' })
  const before = await row.boundingBox(), tableBefore = await table.boundingBox()
  const summary = await page.getByLabel('Component summary').innerText()
  await page.evaluate(() => { const s = window.backendTest; s.emit({ type: 'components', components: s.snapshot.components.map(c => ({ ...c, status: 'Checking' })) }) })
  await expect(row).toContainText('Checking')
  await expect(row.locator('.lattice-loader')).toBeVisible()
  await expect(row.locator('.spin')).toHaveCount(0)
  const during = await row.boundingBox(), tableDuring = await table.boundingBox()
  expect(during!.height).toBe(before!.height); expect(during!.y).toBe(before!.y)
  expect(tableDuring).toEqual(tableBefore)
  await expect(page.getByLabel('Component summary')).toHaveText(summary, { useInnerText: true })
  const badge = row.locator('.status-badge'), heading = table.getByRole('columnheader', { name: 'STATUS' })
  const b = (await badge.boundingBox())!, h = (await heading.boundingBox())!
  expect(Math.abs(b.x + b.width / 2 - h.x - h.width / 2)).toBeLessThan(1)
  await page.getByRole('group', { name: 'Filter components' }).getByRole('button', { name: /^Ready/ }).click()
  await expect(page.getByTestId('component-adb')).toBeVisible(); await expect(page.getByTestId('component-fastboot')).toBeVisible()
  await page.screenshot({ path: `test-results/components-checking-${density}.png` })
})
test('Reading applications shows preparation without a pretend percentage, then measured counts', async ({ page }) => {
  await connectionEvent(page, { devices: [{ id: 'USB1', serial: 'USB1', name: 'Phone', method: 'USB', status: 'connected', android: '13', endpoint: 'USB1', lastSeen: '', known: true, canDetach: false }], activeDeviceId: 'USB1' })
  await page.evaluate(() => { const s = window.backendTest; s.emit({ type: 'apps', apps: { ...s.snapshot.apps, deviceId: 'USB1', userId: 0, status: 'loading', progress: null, message: 'Checking Android profiles…' } }) })
  await page.getByRole('navigation').getByRole('button', { name: 'Apps', exact: true }).click()
  const bar = page.getByRole('progressbar', { name: 'Overall operation progress' })
  await expect(page.getByRole('progressbar')).toHaveCount(0)
  await expect(page.locator('main').getByRole('progressbar')).toHaveCount(0)
  await expect(page.getByLabel('Workspace operations')).toContainText('Total not yet known')
  await page.evaluate(() => { const s = window.backendTest; s.emit({ type: 'apps', apps: { ...s.snapshot.apps, progress: { completed: 155, total: 622 }, message: 'Reading applications and icons for Owner (ID 0)…' } }) })
  expect(Number(await bar.getAttribute('aria-valuenow'))).toBeCloseTo(155 / 622 * 100)
  await expect(bar).toHaveAttribute('aria-valuetext', '155 / 622 applications · 24%')
  await expect(page.getByRole('button', { name: 'Reading applications', exact: true })).toHaveAttribute('title', /155 \/ 622 applications · 24%/)
  await page.screenshot({ path: 'test-results/apps-reading-progress.png' })
  await page.getByRole('navigation').getByRole('button', { name: 'Components', exact: true }).click()
  await expect(page.getByRole('progressbar')).toHaveCount(1)
  await expect(bar).toBeVisible()
  await page.getByRole('navigation').getByRole('button', { name: 'Apps', exact: true }).click()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.evaluate(() => { const s = window.backendTest; s.emit({ type: 'apps', apps: { ...s.snapshot.apps, progress: null } }) })
  await expect(bar).toHaveCount(0)
  await expect(page.getByLabel('Workspace operations').locator('.operation-spinner, .indeterminate')).toHaveCount(0)
  await page.evaluate(() => { const s = window.backendTest; s.emit({ type: 'apps', apps: { ...s.snapshot.apps, status: 'error', progress: null, error: 'Disconnected' } }) })
  await expect(bar).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Could not read applications' })).toBeVisible()
})
