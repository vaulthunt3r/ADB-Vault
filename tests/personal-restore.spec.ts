test('removed apps have separate selection and restoration is limited to available APKs in the active profile', async ({ page }) => {
  await phone(page); await openApps(page)
  await page.evaluate(app => window.backendTest.emit({ type: 'apps', apps: { ...window.backendTest.snapshot.apps, removedApps: [{ ...app, packageName: 'org.example.removed', label: 'Removed system app', installed: false }, { ...app, packageName: 'org.example.missing', label: 'Missing APK app', apkSizeBytes: null, installed: false }] } }), app)
  await page.getByRole('button', { name: 'Removed apps', exact: true }).click()
  const region = page.getByRole('region', { name: 'Removed applications', exact: true })
  await expect(region.locator('.removed-app-row')).toHaveCount(2)
  const missing = region.locator('.removed-app-row').filter({ hasText: 'Missing APK app' }), available = region.locator('.removed-app-row').filter({ hasText: 'Removed system app' })
  await missing.getByRole('button', { name: 'Details for Missing APK app' }).click()
  await expect(page.getByRole('button', { name: 'Restore to profile', exact: true })).toBeDisabled()
  await available.getByRole('button', { name: 'Details for Removed system app' }).click()
  await page.getByRole('tab', { name: 'Actions', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Uninstall from profile', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Restore to profile', exact: true }).click()
  expect(await page.evaluate(() => window.backendTest.requests.filter(r => r.type === 'apps.action'))).toEqual([{ type: 'apps.action', action: 'install-existing', id: 'A', userId: 0, packageName: 'org.example.removed' }])
  await page.screenshot({ path: 'test-results/removed-applications.png' })
  await page.evaluate(app => window.backendTest.emit({ type: 'apps', apps: { ...window.backendTest.snapshot.apps, apps: [...window.backendTest.snapshot.apps.apps, { ...app, label: 'Restored app', packageName: 'org.example.removed' }], removedApps: window.backendTest.snapshot.apps.removedApps!.filter(a => a.packageName !== 'org.example.removed') } }), app)
  await expect(region.locator('.removed-app-row')).toHaveCount(1)
  await region.getByRole('button', { name: 'Apps', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Details for Restored app' })).toBeVisible()
})

test('removed table selects filtered rows, retains hidden choices and sends one profile-scoped restore plan', async ({ page }) => {
  await phone(page); await openApps(page)
  await page.evaluate(app => window.backendTest.emit({ type: 'apps', apps: { ...window.backendTest.snapshot.apps, removedApps: ['Alpha', 'Beta', 'Missing'].map(label => ({ ...app, label, packageName: `org.example.${label.toLowerCase()}`, installed: false, apkSizeBytes: label === 'Missing' ? null : app.apkSizeBytes })) } }), app)
  await page.getByRole('button', { name: 'Removed apps', exact: true }).click()
  const region = page.getByRole('region', { name: 'Removed applications', exact: true })
  const table = region.getByRole('table', { name: 'Removed applications' })
  await expect(table.getByRole('row')).toHaveCount(4)
  await region.getByRole('searchbox').fill('Alpha')
  await table.getByRole('checkbox', { name: 'Select all filtered removed applications' }).check()
  await region.getByRole('searchbox').fill('Beta')
  await expect(region).toContainText('1 hidden by filters')
  await table.getByRole('checkbox', { name: 'Select all filtered removed applications' }).check()
  await region.getByRole('searchbox').fill('')
  await table.getByRole('checkbox', { name: 'Select Missing (org.example.missing)' }).check()
  await expect(region).toContainText('Selected 3 · 1 unavailable')
  await table.getByRole('button', { name: 'Application', exact: true }).click()
  await expect(table.locator('tbody tr').first()).toContainText('Missing')
  const height = await table.locator('tbody tr').first().evaluate(row => row.getBoundingClientRect().height)
  expect(height).toBeLessThanOrEqual(62)
  await region.getByRole('button', { name: 'Restore selected (2)' }).click()
  expect(await page.evaluate(() => window.backendTest.requests.filter(r => r.type === 'apps.batchAction'))).toEqual([{ type: 'apps.batchAction', plan: { id: 'A', userId: 0, packages: ['org.example.alpha', 'org.example.beta', 'org.example.missing'], action: 'install-existing' } }])
  await page.screenshot({ path: 'test-results/removed-table-selection.png' })
  await phone(page, 'B')
  await openApps(page)
  await expect(region.getByRole('button', { name: 'Restore selected (0)' })).toBeDisabled()
  await expect(region).not.toContainText('Selected 3')
})

test('removed selection is pruned after restoration and cleared on profile switch; batch results remain accessible', async ({ page }) => {
  await phone(page); await openApps(page)
  const removed = { ...app, installed: false }
  await page.evaluate(app => window.backendTest.emit({ type: 'apps', apps: { ...window.backendTest.snapshot.apps, apps: [], removedApps: [app] } }), removed)
  await page.getByRole('button', { name: 'Removed apps', exact: true }).click()
  const region = page.getByRole('region', { name: 'Removed applications', exact: true })
  await region.getByRole('checkbox', { name: 'Select all filtered removed applications' }).check()
  await page.evaluate(app => window.backendTest.emit({ type: 'apps', apps: { ...window.backendTest.snapshot.apps, userId: 10, removedApps: [{ ...app, userId: 10 }] } }), removed)
  await expect(region.getByRole('button', { name: 'Restore selected (0)' })).toBeDisabled()
  await region.getByRole('checkbox', { name: 'Select all filtered removed applications' }).check()
  await page.evaluate(app => {
    window.backendTest.emit({ type: 'appAction', state: { id: 'A', userId: 10, packageName: app.packageName, action: 'install-existing', status: 'success', message: '1 completed', batch: { stopRequested: false, deviceName: 'Phone A', profileName: 'Work', items: [{ ...app, status: 'success', message: 'Restored and verified.' }] } } })
    window.backendTest.emit({ type: 'apps', apps: { ...window.backendTest.snapshot.apps, apps: [{ ...app, userId: 10, installed: true }], removedApps: [] } })
  }, removed)
  await expect(region.getByRole('button', { name: 'Restore selected (0)' })).toBeDisabled()
  await region.getByText('Results (1)', { exact: true }).click()
  await expect(region).toContainText('Restored and verified.')
  await expect(region.getByRole('button', { name: 'Show in Activity' })).toBeVisible()
})
