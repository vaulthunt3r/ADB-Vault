import { test, expect, type Page } from '@playwright/test'
import { installBackendFixture, connectionEvent } from './backend-fixture'
import type { AndroidApp } from '../electron/apps-protocol'
const app: AndroidApp = { packageName: 'org.example.app', label: 'Example app', versionName: '2.1', versionCode: 21, uid: 10001, userId: 0, enabled: true, system: true, updatedSystemApp: false, sourceDir: '/system/app/Example/base.apk', apkSizeBytes: 1200000, firstInstallTime: 0, lastUpdateTime: 0, targetSdk: 35, minSdk: 26, installer: null, enabledState: 0, suspended: false, stopped: false, debuggable: false, iconPng: null }
test.beforeEach(async ({ page }) => { await installBackendFixture(page); await page.goto('/') })
async function phone(page: Page, id = 'A') {
  await connectionEvent(page, { devices: [{ id, serial: id, name: `Phone ${id}`, status: 'connected', android: '16', method: 'USB', endpoint: id, lastSeen: '', known: true, canDetach: false }], activeDeviceId: id })
  await page.evaluate(({ app, id }) => { window.backendTest.emit({ type: 'apps', apps: { ...window.backendTest.snapshot.apps, apps: [app], removedApps: [], deviceId: id, userId: 0, status: 'ready', profiles: [{ id: 0, name: 'Owner', managed: false, running: true }] } }) }, { app, id })
}
async function openApps(page: Page) { await page.getByRole('navigation').getByRole('button', { name: 'Apps', exact: true }).click() }

test('personal badges follow the package onto another phone and preserve original phone metadata', async ({ page }) => {
  await phone(page); await openApps(page)
  await page.getByRole('button', { name: 'Details for Example app', exact: true }).click()
  await page.getByRole('button', { name: 'Personal · add note', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Personal records · Example app' })
  await dialog.getByRole('button', { name: 'Add record' }).click()
  await dialog.getByRole('textbox', { name: 'Personal badge', exact: true }).fill('Не удалять')
  await dialog.getByRole('textbox', { name: 'Note', exact: true }).fill('Нужно для функции телефона. Проверено на Phone A.')
  await dialog.getByRole('button', { name: 'Save record' }).click()
  await expect(dialog.locator('.personal-record')).toContainText('Phone A')
  await dialog.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Details for Example app' })).toContainText('Не удалять')
  await phone(page, 'B'); await openApps(page)
  await page.getByRole('button', { name: 'Details for Example app', exact: true }).click()
  await page.getByRole('button', { name: 'Personal (1)', exact: true }).click()
  await expect(dialog.locator('.personal-record .personal-provenance')).toContainText('Phone A')
  await dialog.getByText('Original phone and app version').click()
  await expect(dialog.locator('.personal-origin')).toContainText('2.1 (21)')
  await dialog.getByRole('button', { name: 'Edit record', exact: true }).click()
  await dialog.getByRole('textbox', { name: 'Note', exact: true }).fill('Проверено и на втором телефоне.')
  await dialog.getByRole('button', { name: 'Save record' }).click()
  await expect(dialog.locator('.personal-record')).toContainText('Phone A')
  await page.screenshot({ path: 'test-results/personal-app-record.png' })
  const requests = await page.evaluate(() => window.backendTest.requests.filter(r => r.type === 'apps.notesSave'))
  expect(requests[0]).toMatchObject({ note: { target: { id: 'A', packageName: app.packageName, userId: 0 } } })
})

test('personal library works without a phone, searches and exports/imports, and deletes only its record', async ({ page }) => {
  await openApps(page); await page.getByRole('button', { name: 'Personal database', exact: true }).click()
  const library = page.getByRole('region', { name: 'Personal database', exact: true })
  await library.getByRole('button', { name: 'Add record' }).click()
  await library.getByRole('textbox', { name: 'Package name' }).fill('org.example.offline')
  await library.getByRole('textbox', { name: 'Note', exact: true }).fill('Remember this app even without a phone.')
  await library.getByRole('button', { name: 'Save record' }).click()
  await expect(library.locator('.personal-record')).toContainText('On this PC')
  await library.getByRole('searchbox', { name: 'Search records' }).fill('unmatched')
  await expect(library.locator('.personal-record')).toHaveCount(0)
  await library.getByRole('searchbox', { name: 'Search records' }).fill('offline')
  await expect(library.locator('.personal-record')).toHaveCount(1)
  await library.getByRole('button', { name: 'Export', exact: true }).click()
  await library.getByRole('button', { name: 'Import', exact: true }).click()
  await page.setViewportSize({ width: 1000, height: 720 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/personal-database.png' })
  await library.getByRole('button', { name: 'Delete record', exact: true }).click()
  await expect(library.locator('.personal-record')).toHaveCount(0)
  expect(await page.evaluate(() => window.backendTest.requests.filter(r => ['apps.notesExport', 'apps.notesImport'].includes(r.type)).map(r => r.type))).toEqual(['apps.notesExport', 'apps.notesImport'])
})

test('removed apps have separate selection and restoration is limited to available APKs in the active profile', async ({ page }) => {
  await phone(page); await openApps(page)
  await page.evaluate(app => window.backendTest.emit({ type: 'apps', apps: { ...window.backendTest.snapshot.apps, removedApps: [{ ...app, packageName: 'org.example.removed', label: 'Removed system app', installed: false }, { ...app, packageName: 'org.example.missing', label: 'Missing APK app', apkSizeBytes: null, installed: false }] } }), app)
  await page.getByRole('button', { name: 'Removed apps', exact: true }).click()
  const region = page.getByRole('region', { name: 'Removed applications', exact: true })
  await expect(region.locator('.removed-app-row')).toHaveCount(2)
  const missing = region.locator('.removed-app-row').filter({ hasText: 'Missing APK app' }), available = region.locator('.removed-app-row').filter({ hasText: 'Removed system app' })
  await expect(missing.getByRole('button', { name: 'Restore to profile' })).toBeDisabled()
  await available.getByRole('button', { name: 'Removed system app' }).click()
  await page.getByRole('tab', { name: 'Actions', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Uninstall from profile', exact: true })).toHaveCount(0)
  await available.getByRole('button', { name: 'Restore to profile' }).click()
  expect(await page.evaluate(() => window.backendTest.requests.filter(r => r.type === 'apps.action'))).toEqual([{ type: 'apps.action', action: 'install-existing', id: 'A', userId: 0, packageName: 'org.example.removed' }])
  await page.screenshot({ path: 'test-results/removed-applications.png' })
  await page.evaluate(app => window.backendTest.emit({ type: 'apps', apps: { ...window.backendTest.snapshot.apps, apps: [...window.backendTest.snapshot.apps.apps, { ...app, label: 'Restored app', packageName: 'org.example.removed' }], removedApps: window.backendTest.snapshot.apps.removedApps!.filter(a => a.packageName !== 'org.example.removed') } }), app)
  await expect(region.locator('.removed-app-row')).toHaveCount(1)
  await region.getByRole('button', { name: 'Apps', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Details for Restored app' })).toBeVisible()
})
