test('every component exposes its source through the desktop bridge', async ({ page }) => {
  await page.evaluate(databases => window.backendTest.emit({ type: 'components', components: [...window.backendTest.snapshot.components, ...databases] }), databaseCatalog)
  for (const component of [...componentCatalog, ...databaseCatalog]) {
    await page.getByRole('button', { name: `Select ${component.name}`, exact: true }).click()
    const link = page.getByRole('link', { name: component.sourceUrl!, exact: true })
    await expect(link).toHaveAttribute('href', component.sourceUrl!)
    await expect(link).toHaveText(component.sourceUrl!)
    await page.getByRole('button', { name: 'Copy source URL', exact: true }).click()
    expect(await page.evaluate(() => window.backendTest.clipboardWrites.at(-1))).toBe(component.sourceUrl)
    await expect(page.getByText('Copied', { exact: true })).toBeVisible()
    await link.click()
    expect(await page.evaluate(() => window.backendTest.requests.at(-1))).toEqual({ type: 'components.source', id: component.id })
  }
})

