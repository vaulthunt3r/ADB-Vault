test('preparation targets the original app and presents files and hashes without claiming upload', async ({ page }) => {
  await page.evaluate(() => {
    const request = window.desktop!.request
    window.desktop!.request = async r => {
      if (r.type !== 'apps.prepareScan') return request(r)
      window.backendTest.requests.push(r)
      return { ok: true, snapshot: window.backendTest.snapshot, scanPreparation: { directory: 'C:\\Scans\\Notes', message: '', files: [{ file: 'org.example.notes.apk', sha256: 'a'.repeat(64) }, { file: 'org.example.notes.split-001.apk', sha256: 'b'.repeat(64) }] } }
    }
  })
  await page.getByRole('button', { name: 'Find online…', exact: true }).click()
  await page.getByRole('button', { name: 'Scanners', exact: true }).click()
  await page.getByRole('button', { name: 'Jotti', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Check with Jotti' })
  await dialog.getByRole('button', { name: 'Prepare APK files & open website' }).click()
  await expect(dialog).toContainText('Prepared locally · Not uploaded')
  expect(await page.evaluate(() => window.backendTest.requests.at(-1))).toEqual({ type: 'apps.prepareScan', id: 'USB1', userId: 10, packageName: application.packageName, url: 'https://virusscan.jotti.org/' })
  await dialog.getByRole('button', { name: 'Copy SHA-256 of org.example.notes.apk', exact: true }).click()
  expect(await page.evaluate(() => window.backendTest.clipboardWrites.at(-1))).toBe('a'.repeat(64))
})
