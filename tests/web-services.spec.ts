test('service order is independent by category, includes disabled and custom entries, and persists in Find online', async ({ page }) => {
  await page.getByRole('button', { name: 'Find online…', exact: true }).click()
  await page.getByRole('button', { name: 'Configure services…' }).click()
  const searches = page.getByRole('region', { name: 'Search websites', exact: true })
  const scanners = page.getByRole('region', { name: 'File scanners', exact: true })
  const originalSearches = await searches.locator('.web-service-row strong').allTextContents()
  const originalScanners = await scanners.locator('.web-service-row strong').allTextContents()
  const handle = (name: string) => page.getByRole('button', { name: `Reorder ${name}`, exact: true })
  const row = (name: string) => page.locator('.web-service-row').filter({ has: handle(name) })
  await handle('Google Play').press('ArrowUp')
  await expect(searches.locator('.web-service-row strong')).toHaveText(originalSearches)
  await handle('Koodous').press('ArrowDown')
  await expect(scanners.locator('.web-service-row strong')).toHaveText(originalScanners)
  await handle('Google').dragTo(row('Google Play'))
  await expect(searches.locator('.web-service-row strong').first()).toHaveText('Google')
  await handle('Google').press('ArrowDown')
  await expect(searches.locator('.web-service-row strong')).toHaveText(originalSearches)
  await handle('Google').press('ArrowUp')
  await page.getByRole('button', { name: 'Reset Google', exact: true }).click()
  await page.getByLabel('Enable Google Play', { exact: true }).uncheck()
  await handle('Google Play').press('ArrowDown')
  await expect(scanners.locator('.web-service-row strong')).toHaveText(originalScanners)
  await handle('VirusTotal').dragTo(row('FileScan.io'))
  const expectedScanners = ['VirusTotal', ...originalScanners.filter(name => name !== 'VirusTotal')]
  await page.getByRole('button', { name: 'Add service', exact: true }).click()
  await expect(handle('Google')).toBeDisabled()
  await page.getByLabel('Name', { exact: true }).fill('My search')
  await page.getByLabel('HTTPS URL template').fill('https://example.org/?q={query}')
  await page.getByRole('button', { name: 'Save service' }).click()
  await handle('My search').dragTo(row('Bing'))
  const expectedSearches = ['Google', 'DuckDuckGo', 'Google Play', ...originalSearches.slice(3, -1), 'My search', 'Bing']
  await expect(searches.locator('.web-service-row strong')).toHaveText(expectedSearches)
  await expect(scanners.locator('.web-service-row strong')).toHaveText(expectedScanners)
  await handle('Bing').dragTo(row('VirusTotal'))
  await expect(searches.locator('.web-service-row strong')).toHaveText(expectedSearches)
  await expect(scanners.locator('.web-service-row strong')).toHaveText(expectedScanners)
  await expect(page.locator('.web-service-row.dragging, .web-service-row.drop-target')).toHaveCount(0)
  await page.reload()
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('button', { name: 'Web services', exact: true }).click()
  await expect(searches.locator('.web-service-row strong')).toHaveText(expectedSearches)
  await expect(scanners.locator('.web-service-row strong')).toHaveText(expectedScanners)
  await expect(page.getByLabel('Enable Google Play', { exact: true })).not.toBeChecked()
  await page.setViewportSize({ width: 1000, height: 680 })
  await page.getByRole('heading', { name: 'Search & scanners', exact: true }).scrollIntoViewIfNeeded()
  expect(await page.locator('main').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/web-service-order.png' })
  await connectionEvent(page, { devices: [{ id: 'USB1', serial: 'USB1', name: 'Phone', status: 'connected', android: '16', method: 'USB', endpoint: 'USB1', lastSeen: '', known: true, canDetach: false }], activeDeviceId: 'USB1' })
  await page.evaluate(app => { Object.assign(window.backendTest.snapshot.apps, { apps: [app], userId: 10, profiles: [{ id: 10, name: 'Work', managed: true, running: true }] }) }, application)
  await page.getByRole('navigation').getByRole('button', { name: 'Apps', exact: true }).click()
  await page.getByRole('button', { name: 'Details for Notes & ideas', exact: true }).click()
  await page.getByRole('button', { name: 'Find online…', exact: true }).click()
  const menu = page.getByRole('dialog', { name: 'Find application online' })
  const menuNames = () => menu.locator('.web-service-menu > button > span').evaluateAll(elements => elements.map(el => el.firstChild?.textContent))
  await expect.poll(menuNames).toEqual(expectedSearches.filter(name => name !== 'Google Play'))
  await menu.getByRole('button', { name: 'Scanners', exact: true }).click()
  await expect.poll(menuNames).toEqual(expectedScanners)
})
