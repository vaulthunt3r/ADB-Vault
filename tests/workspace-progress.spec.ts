  await page.getByRole('navigation').getByRole('button', { name: 'Apps', exact: true }).click()
  await page.evaluate(() => window.backendTest.emit({ type: 'backup', state: { id: 'phone', userId: 0, name: 'User', format: 'auto', operation: 'backup', status: 'running', message: 'Notes: Copying to computer: base.apk', completed: 0, total: 2, items: [{ packageName: 'org.example.notes', label: 'Notes', status: 'running' }, { packageName: 'org.example.next', label: 'Next', status: 'pending' }] } }))
