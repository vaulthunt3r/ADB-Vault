import { test, expect, type Page } from '@playwright/test'
import { installBackendFixture } from './backend-fixture'

async function appearance(page: Page) {
  await page.getByRole('navigation').getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('group', { name: 'Settings categories' }).getByRole('button', { name: 'Appearance', exact: true }).click()
}
test.beforeEach(async ({ page }) => { await installBackendFixture(page); await page.goto('/') })

test('Amber remembers its color, follows pinning, and returns to the ordinary theme', async ({ page }, testInfo) => {
  await appearance(page)
  await page.getByRole('button', { name: 'Theme Air', exact: true }).click()
  const toggle = page.getByRole('button', { name: 'Terminal mode', exact: true })
  await toggle.dblclick()
  await expect(page.getByRole('radio', { name: 'Green phosphor' })).toBeChecked()
  await page.getByRole('radio', { name: 'Amber phosphor' }).check()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'terminal-easter-egg-amber')
  await expect(page.locator('html')).toHaveAttribute('data-terminal-mode', 'true')
  await expect(page.locator('.appearance-current')).toContainText('Zero Cool Amber')
  await expect(page.locator('.section-inspector-title')).toHaveText('Zero Cool Amber')
  await page.getByRole('checkbox', { name: 'Show Zero Cool in theme options', exact: true }).check()
  await page.getByRole('button', { name: 'Theme Zero Cool', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'terminal-easter-egg')
  await page.getByRole('button', { name: 'Theme Zero Cool Amber', exact: true }).click()
  await page.getByRole('navigation').getByRole('button', { name: 'Components', exact: true }).click()
  await expect(page.locator('body')).toHaveCSS('color', 'rgb(255, 182, 92)')
  await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(0, 0, 0)')
  await expect(page.locator('.nav-item.active')).toHaveCSS('border-radius', '0px')
  await page.screenshot({ path: testInfo.outputPath('zero-cool-amber.png') })
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'air')
  await toggle.dblclick()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'terminal-easter-egg-amber')
  await expect(page.locator('.terminal-activation')).toHaveCSS('color', 'rgb(255, 182, 92)')
  await expect(page.locator('.terminal-activation__prompt')).toHaveCSS('color', 'rgb(206, 127, 43)')
  await toggle.click({ button: 'right' })
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'terminal-easter-egg-amber')
  await expect(page.getByLabel('Zero Cool pinned', { exact: true })).toBeVisible()
  await appearance(page)
  await page.getByRole('radio', { name: 'Green phosphor' }).check()
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'terminal-easter-egg')
  await expect(page.getByLabel('Zero Cool pinned', { exact: true })).toBeVisible()
  await toggle.dblclick()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'air')
  await expect(page.locator('html')).toHaveAttribute('data-terminal-mode', 'false')
  await appearance(page)
  await page.getByRole('radio', { name: 'Amber phosphor' }).check()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'air')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'air')
  await toggle.dblclick()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'terminal-easter-egg-amber')
})

for (const removed of ['glass-light', 'glass-dark', 'material-light', 'material-dark']) {
  test(`saved ${removed} falls back to Air and keeps independent preferences`, async ({ page }) => {
    await page.evaluate(themeId => localStorage.setItem('adb-vault-appearance', JSON.stringify({ state: { themeId, density: 'compact', cornerStyle: 'square', zenMode: true }, version: 1 })), removed)
    await page.reload()
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'air')
    await expect(page.locator('html')).toHaveAttribute('data-theme-family', 'classic')
    await expect(page.locator('html')).toHaveAttribute('data-corner-style', 'square')
    await expect(page.locator('html')).toHaveAttribute('data-zen-mode', 'true')
    await expect(page.locator('main')).toHaveClass(/density-compact/)
    await appearance(page)
    await expect(page.getByRole('button', { name: /^Theme (Glass|Material)/ })).toHaveCount(0)
    await page.getByRole('button', { name: 'Terminal mode', exact: true }).dblclick()
    await expect(page.getByRole('radio', { name: 'Green phosphor' })).toBeChecked()
  })
}
