import { test, expect } from '@playwright/test'
import { installBackendFixture } from './backend-fixture'

test.beforeEach(async ({ page }) => { await installBackendFixture(page) })

test('all four title presets repeat without shifting the header; choices persist only as Zero Cool effects', async ({ page }) => {
  await page.clock.install()
  await page.goto('/')
  const title = page.locator('.zero-cool-title')
  const toggle = page.getByRole('button', { name: 'Terminal mode', exact: true })
  await expect(title).toHaveCount(0)
  await page.getByRole('navigation').getByRole('button', { name: 'Settings', exact: true }).click()
  await expect(page.getByRole('group', { name: 'Zero Cool text animations' })).toHaveCount(0)
  await toggle.dblclick()
  await expect(title).toHaveAttribute('data-preset', 'terminal')
  await toggle.click({ button: 'right' })
  const presets = page.getByRole('combobox', { name: 'Animation preset', exact: true })
  await expect(presets.locator('option')).toHaveText(['Classic', 'Terminal', 'Flip', 'Loop', 'Random'])
  const glyphs = title.locator(':scope > span[aria-hidden="true"]')
  for (const preset of ['classic', 'terminal', 'flip', 'loop']) {
    await presets.selectOption(preset)
    await expect(title).toHaveAttribute('data-preset', preset)
    await expect(title).toHaveAttribute('data-repeat', 'true')
    await expect(title.locator('.zero-cool-title-scrambled').first()).toBeAttached()
    const initial = (await title.boundingBox())!
    await page.clock.runFor(1000)
    await expect(glyphs).toHaveText('ADB Vault')
    await expect(title.locator('.zero-cool-title-scrambled')).toHaveCount(0)
    const settled = (await title.boundingBox())!
    expect(Math.abs(initial.width - settled.width)).toBeLessThan(1)
    // Prove it runs again without a mouse gesture after the readable pause.
    let repeated = false
    for (let i = 0; i < 30 && !repeated; i++) {
      await page.clock.runFor(80)
      repeated = await title.locator('.zero-cool-title-scrambled').count() > 0
    }
    expect(repeated, `${preset} repeats`).toBe(true)
    expect(Math.abs((await title.boundingBox())!.width - settled.width)).toBeLessThan(1)
  }
  await page.getByRole('checkbox', { name: 'Repeat title animation', exact: true }).uncheck()
  await expect(title).toHaveAttribute('data-repeat', 'false')
  await page.clock.runFor(8000)
  await expect(glyphs).toHaveText('ADB Vault')
  await expect(title.locator('.zero-cool-title-scrambled')).toHaveCount(0)
  await page.reload()
  await expect(title).toHaveAttribute('data-preset', 'loop')
  await expect(title).toHaveAttribute('data-repeat', 'false')
  await page.getByRole('navigation').getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Animate ADB Vault', exact: true }).uncheck()
  await expect(title).toHaveCount(0)
  await expect(page.locator('.zero-cool-title-static')).toHaveText('ADB Vault')
  await expect(presets).toBeEnabled() // Quotes can remain animated independently.
  await page.getByRole('checkbox', { name: 'Animate movie quotes', exact: true }).uncheck()
  await expect(presets).toBeDisabled()
  await page.reload()
  await expect(title).toHaveCount(0)
  await page.getByRole('navigation').getByRole('button', { name: 'Settings', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Animate ADB Vault', exact: true })).not.toBeChecked()
  await page.getByRole('checkbox', { name: 'Animate ADB Vault', exact: true }).check()
  await page.getByRole('radio', { name: 'Amber phosphor', exact: true }).check()
  await presets.selectOption('terminal')
  await expect(title).toHaveAttribute('data-preset', 'terminal')
  await expect(title.locator('.zero-cool-title-scrambled').first()).toHaveCSS('color', 'rgb(206, 127, 43)')
  await page.setViewportSize({ width: 1000, height: 680 })
  await page.clock.runFor(4000)
  const header = page.locator('.titlebar')
  expect(await header.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.locator('.zero-cool-title-settings').scrollIntoViewIfNeeded()
  await page.screenshot({ path: 'test-results/zero-cool-title-amber.png' })
  await page.getByRole('button', { name: 'Theme Paper', exact: true }).click()
  await expect(title).toHaveCount(0)
  await expect(page.getByRole('group', { name: 'Zero Cool text animations' })).toHaveCount(0)
  await expect(page.locator('.app-wordmark')).toContainText('ADB Vault')
})

test('title animation stops for reduced motion and a hidden window, then resumes', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.clock.install()
  await page.goto('/')
  await page.getByRole('button', { name: 'Terminal mode', exact: true }).dblclick()
  const title = page.locator('.zero-cool-title')
  await expect(title).toHaveCount(0)
  await expect(page.locator('.zero-cool-title-static')).toHaveText('ADB Vault')
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await expect(title).toHaveAttribute('data-preset', 'terminal')
  await page.clock.runFor(1000)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(title).toHaveCount(0)
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await expect(title).toHaveCount(1)
  // Emulate the document visibility notification used by minimized Electron windows.
  await page.evaluate(() => {
    Object.defineProperty(document, 'hidden', { configurable: true, value: true })
    document.dispatchEvent(new Event('visibilitychange'))
  })
  await expect(title).toHaveCount(0)
  await page.clock.runFor(10_000)
  await expect(page.locator('.zero-cool-title-static')).toHaveText('ADB Vault')
  await page.evaluate(() => {
    Object.defineProperty(document, 'hidden', { configurable: true, value: false })
    document.dispatchEvent(new Event('visibilitychange'))
  })
  await expect(title).toHaveCount(1)
  await page.clock.runFor(1000)
  await expect(title.locator(':scope > span[aria-hidden="true"]')).toHaveText('ADB Vault')
})

test('speed changes the reveal duration and Random chooses a different effect each cycle', async ({ page }) => {
  await page.clock.install()
  await page.goto('/')
  const toggle = page.getByRole('button', { name: 'Terminal mode', exact: true })
  await toggle.dblclick()
  await toggle.click({ button: 'right' })
  await page.getByRole('navigation').getByRole('button', { name: 'Settings', exact: true }).click()
  const title = page.locator('.zero-cool-title')
  const glyphs = title.locator(':scope > span[aria-hidden="true"]')
  const speed = page.getByRole('slider', { name: 'Animation speed', exact: true })
  const repeat = page.getByRole('checkbox', { name: 'Repeat title animation', exact: true })
  await repeat.uncheck()
  await speed.focus()
  await speed.press('End')
  await expect(title).toHaveAttribute('data-speed', '2')
  await page.clock.runFor(220)
  await expect(title.locator('.zero-cool-title-scrambled')).toHaveCount(0)
  await expect(glyphs).toHaveText('ADB Vault')
  await speed.press('Home')
  await expect(title).toHaveAttribute('data-speed', '0.5')
  await page.clock.runFor(220)
  expect(await title.locator('.zero-cool-title-scrambled').count()).toBeGreaterThan(0)
  await page.clock.runFor(800)
  await expect(glyphs).toHaveText('ADB Vault')
  await speed.press('End')
  await page.getByRole('combobox', { name: 'Animation preset', exact: true }).selectOption('random')
  await repeat.check()
  await expect(title).toHaveAttribute('data-preset', 'random')
  let last = await title.getAttribute('data-effect')
  for (let cycle = 0; cycle < 3; cycle++) {
    await page.clock.runFor(600)
    await expect(glyphs).toHaveText('ADB Vault')
    await expect(title).toHaveAttribute('data-effect', last!)
    let next = last
    for (let tick = 0; tick < 35 && next === last; tick++) {
      await page.clock.runFor(80)
      next = await title.getAttribute('data-effect')
    }
    expect(['classic', 'terminal', 'flip', 'loop']).toContain(next)
    expect(next).not.toBe(last)
    last = next
  }
  await repeat.uncheck()
  last = await title.getAttribute('data-effect')
  await page.clock.runFor(10_000)
  await expect(title).toHaveAttribute('data-effect', last!)
  await expect(glyphs).toHaveText('ADB Vault')
  await speed.focus()
  await speed.press('ArrowLeft')
  await expect(speed).toHaveValue('1.75')
  await page.reload()
  await expect(title).toHaveAttribute('data-preset', 'random')
  await expect(title).toHaveAttribute('data-speed', '1.75')
  await expect(title).toHaveAttribute('data-repeat', 'false')
})

test('movie quotes use every preset once, remain readable on hover, and can be disabled separately', async ({ page }) => {
  await page.clock.install()
  await page.goto('/')
  const toggle = page.getByRole('button', { name: 'Terminal mode', exact: true })
  await toggle.dblclick()
  await page.getByRole('navigation').getByRole('button', { name: 'Settings', exact: true }).click()
  const presets = page.getByRole('combobox', { name: 'Animation preset', exact: true })
  const tooltip = page.getByRole('tooltip')
  const quote = tooltip.locator('.zero-cool-quote')
  for (const preset of ['classic', 'terminal', 'flip', 'loop', 'random']) {
    await presets.selectOption(preset)
    await toggle.hover()
    await expect(quote).toHaveAttribute('data-preset', preset)
    await expect(quote).toHaveAttribute('data-repeat', 'false')
    const name = (await tooltip.getAttribute('aria-label'))!
    await expect(toggle).toHaveAccessibleDescription(name)
    const initial = (await tooltip.boundingBox())!
    await page.clock.runFor(4000)
    await expect(quote.locator(':scope > span[aria-hidden="true"]')).toHaveText(name.replace(' — Hackers · 1995', ''))
    await tooltip.hover()
    await page.clock.runFor(8000)
    await expect(quote.locator('.zero-cool-quote-scrambled')).toHaveCount(0)
    const settled = (await tooltip.boundingBox())!
    expect(Math.abs(initial.width - settled.width)).toBeLessThan(1)
    expect(Math.abs(initial.height - settled.height)).toBeLessThan(1)
    await page.mouse.move(800, 18)
    await expect(tooltip).toHaveCount(0)
  }
  const animateQuotes = page.getByRole('checkbox', { name: 'Animate movie quotes', exact: true })
  await animateQuotes.uncheck()
  await toggle.hover()
  await expect(tooltip.locator('.zero-cool-quote-static')).toBeVisible()
  await expect(page.locator('.zero-cool-title')).toHaveCount(1)
  await page.mouse.move(800, 18)
  await animateQuotes.check()
  await toggle.hover()
  await expect(quote).toBeVisible()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(tooltip.locator('.zero-cool-quote-static')).toBeVisible()
  await expect(quote).toHaveCount(0)
  await expect(page.locator('.zero-cool-title')).toHaveCount(0)
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await expect(quote).toBeVisible()
  await page.clock.runFor(4000)
  await page.screenshot({ path: 'test-results/zero-cool-movie-quote.png' })
  await toggle.press('Escape')
  await expect(tooltip).toHaveCount(0)
})
